import { useState } from 'react';
import { Link } from 'react-router-dom';
import { useApi } from '../../lib/api.js';
import { PageHead, Async, Tabs, Status, Empty, useAction, ActionMsg } from '../../components/ui.jsx';
import { date, ago, stageLabel, human } from '../../lib/format.js';
import { IntroTable } from './Deal.jsx';

export function HostInterest() {
  const [action, setAction] = useState('interested');
  const q = useApi(`/host/interest${action ? `?action=${action}` : ''}`, [action]);
  return (
    <>
      <PageHead kicker="Investor behaviour" title="Interest" sub="Every swipe is recorded here as it happens. Interest is not a commitment.">
        <a className="btn ghost" href="/api/host/export/interest.csv">Export CSV</a>
        <button className="btn ghost" onClick={() => q.reload()}>Refresh</button>
      </PageHead>
      <Tabs value={action} onChange={setAction} tabs={[{ key: 'interested', label: 'Right swipes' }, { key: 'saved', label: 'Saved' }, { key: 'passed', label: 'Left swipes' }, { key: '', label: 'All' }]} />
      <Async q={q}>{d => (
        <div className="grid g-side">
          {d.swipes.length ? (
            <div className="table-wrap"><table>
              <thead><tr><th>Investor</th><th>Company</th><th>Action</th><th>Fit</th><th>Introduction</th><th>When</th></tr></thead>
              <tbody>{d.swipes.map(s => (
                <tr key={`${s.investor_id}-${s.company_id}`}>
                  <td><Link to={`/host/users/${s.investor_id}`}>{s.investor}</Link><div className="small muted">{s.firm || human(s.investor_type)}</div></td>
                  <td><Link to={`/host/deals/${s.company_id}`}>{s.company}</Link><div className="small muted">{s.industry} · {stageLabel(s.round_stage)}</div></td>
                  <td><Status s={s.action} /></td><td className="mono">{s.score ?? '—'}</td>
                  <td>{s.intro_status ? <Status s={s.intro_status} /> : '—'}</td><td>{date(s.updated_at, true)}</td>
                </tr>
              ))}</tbody>
            </table></div>
          ) : <Empty title="No activity" />}
          <div className="dark card" style={{ padding: 24, alignSelf: 'start' }}>
            <span className="label accent">Event stream</span>
            <div className="timeline" style={{ marginTop: 12 }}>
              {d.events.length ? d.events.slice(0, 30).map(e => <div className="item" key={e.id}><div className="when">{ago(e.created_at)}</div>{e.investor} · {human(e.action)} · {e.company}</div>) : <div className="muted">No events yet.</div>}
            </div>
          </div>
        </div>
      )}</Async>
    </>
  );
}

export function HostIntroductions() {
  const [status, setStatus] = useState('pending');
  const q = useApi(`/host/introductions${status ? `?status=${status}` : ''}`, [status]);
  const a = useAction();
  return (
    <>
      <PageHead kicker="Host-controlled" title="Introductions" sub="Approve, defer or reject introductions and control identity disclosure for each pair." />
      <Tabs value={status} onChange={setStatus} tabs={['pending', 'approved', 'deferred', 'completed', 'rejected', ''].map(s => ({ key: s, label: s || 'All' }))} />
      <ActionMsg a={a} />
      <Async q={q}>{d => d.introductions.length ? <IntroTable rows={d.introductions} a={a} reload={() => q.reload(true)} showCompany /> : <Empty title={`No ${status || ''} introductions`} />}</Async>
    </>
  );
}

export function HostTeasers() {
  const [status, setStatus] = useState('pending_approval');
  const q = useApi(`/host/teasers?status=${status}`, [status]);
  return (
    <>
      <PageHead kicker="Approval queue" title="Approvals" sub="Teasers must be approved before a company appears in investor discovery." />
      <Tabs value={status} onChange={setStatus} tabs={[{ key: 'pending_approval', label: 'Pending' }, { key: 'draft', label: 'Drafts' }, { key: 'approved', label: 'Approved' }, { key: 'rejected', label: 'Rejected' }]} />
      <Async q={q}>{d => d.teasers.length ? (
        <div className="table-wrap"><table><thead><tr><th>Company</th><th>Version</th><th>Generated by</th><th>Created</th><th>Status</th><th /></tr></thead>
          <tbody>{d.teasers.map(t => <tr key={t.id}><td>{t.company}</td><td className="mono">v{t.version}</td><td>{t.generated_by}</td><td>{date(t.created_at, true)}</td><td><Status s={t.status} /></td><td><Link className="btn sm" to={`/host/deals/${t.company_id}`}>Review</Link></td></tr>)}</tbody></table></div>
      ) : <Empty title="Queue is empty" />}</Async>
    </>
  );
}
